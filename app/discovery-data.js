export function familyFor(syllable) {
  const text = syllable.text;
  if (/^(a|à|â|e|é|è|ê|i|o|ô|u|ou|au|eau|eu|ai|an|en|in|on|un|oi)$/.test(text)) return 'vowels';
  if (/^[bcdfgptv][lr]/.test(text)) return 'clusters';
  if (/(an|en|in|on|un|ain|ein|am|em|im|om)$/.test(text)) return 'nasal';
  if (/^(ch|ph|gn)|ou|eau|au|oi|eu|ai|ei/.test(text)) return 'complex';
  if (/^[bcdfghjklmnpqrstvwxyzç][aàâeéèêiîïoôuû]$/.test(text)) return 'simple';
  return 'closed';
}
export function syllablesInFamily(id) { return discoverySyllables.filter(syllable => familyFor(syllable) === id); }
export function wordsForSyllable(id) { return associatedWords.get(id) || []; }
export function wordById(id) { return discoveryWords.find(word => word.id === id); }
export function syllableById(id) { return syllables.get(id); }
export function makeListeningRound(previousId = null, random = Math.random) {
  // Short common words; the target is not printed before answering.
  const allowed = ['papa','papi','moto','vélo','bébé','lama','midi','ami','banane','bateau','ballon','tomate','lapin','sapin','robot','cadeau'];
  const pool = discoveryWords.filter(word => allowed.includes(word.text));
  const options = [...pool].map(word => ({ word, key:random() })).sort((a,b) => a.key-b.key).slice(0,3).map(item => item.word.id);
  const targets = options.filter(id => id !== previousId);
  const target = targets[Math.min(targets.length-1,Math.floor(random()*targets.length))] || options[0];
  return { target, options, heard:false, rejected:[], correct:false };
}
