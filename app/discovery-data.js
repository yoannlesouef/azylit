const seenWords = new Set();
export const discoveryWords = entries.flatMap(([notation,emoji]) => {
  const fixed = notation;
  const parts = fixed.split('/').map(token => { const [text,key] = token.split('~'); return { text, syllable:key || text }; });
  const text = parts.map(part => part.text).join('');
  if (seenWords.has(text)) return [];
  seenWords.add(text);
  return [{ id:'w-' + text, text, emoji, parts }];
});
const soundOverrides = { lis:'lit', til:'ti', let:'lait', vet:'vais', rêt:'raie', mat:'ma', can:'quand', bam:'banc', chan:'champ', gan:'gant', ter:'té', ler:'lé', mer:'mé', noi:'noix', tion:'sion', man:'m’en', pin:'pain', tin:'tain', din:'daim', sin:'saint', lon:'l’on', pis:'pi', bot:'bo', lot:'lo', lat:'la', gat:'ga', ssin:'saint', gi:'ji', ge:'je', xy:'gzi', lli:'li', quai:'ké', che:'cheu', teau:'tôt', reau:'rot', deau:'dos', meau:'mot', phar:'far', zage:'zage', zine:'zine', zette:'zette', qua:'ka', zé:'zé' };
const syllables = new Map();
const associatedWords = new Map();
for (const {syllable,examples} of syllableExamples) {
  const words = examples.map(example => {
    const match = /^([^\[\]]*)\[([^\[\]]+)\]([^\[\]]*)$/.exec(example);
    if (!match) throw new Error('Exemple de syllabe invalide : ' + example);
    const [,before,target,after] = match;
    const text = before + target + after;
    let word = discoveryWords.find(item => item.text === text);
    if (!word) {
      word = {id:'w-' + text,text,emoji:'🔊',parts:[{text,syllable:null}]};
      discoveryWords.push(word);
    }
    const parts = [
      ...(before ? [{text:before,syllable:null}] : []),
      {text:target,syllable},
      ...(after ? [{text:after,syllable:null}] : [])
    ];
    return {...word,parts};
  });
  if (new Set(words.map(word => word.id)).size < 6) throw new Error('Six mots distincts sont nécessaires pour ' + syllable);
  associatedWords.set(syllable,words);
  syllables.set(syllable,{id:syllable,text:syllable,speech:soundOverrides[syllable] || syllable,words:words.map(word => word.id)});
}
